-- =====================
-- PARTE 14 — FUNÇÕES (CÁLCULO)
-- =====================

-- 38
SELECT QUANTIDADE, PRECO_UNITARIO,
       QUANTIDADE * PRECO_UNITARIO AS SUBTOTAL
FROM ITEM_PEDIDO;

-- 39
SELECT SUBTOTAL,
       QUANTIDADE * PRECO_UNITARIO AS CALCULADO
FROM ITEM_PEDIDO;

-- 40
SELECT PED.CODIGO,
       PED.VALOR_TOTAL,
       SUM(IP.QUANTIDADE * IP.PRECO_UNITARIO) AS TOTAL_CALCULADO
FROM PEDIDO PED
INNER JOIN ITEM_PEDIDO IP ON PED.CODIGO = IP.CODIGO_PEDIDO
GROUP BY PED.CODIGO, PED.VALOR_TOTAL;



-- =====================
-- PARTE 13 — MULTI JOIN
-- =====================

-- 34
SELECT P.NOME, PR.NOME, IP.QUANTIDADE
FROM PEDIDO PED
INNER JOIN CLIENTE C ON PED.COD_CLIENTE = C.CODIGO
INNER JOIN PESSOA P ON C.CODIGO = P.CODIGO
INNER JOIN ITEM_PEDIDO IP ON PED.CODIGO = IP.CODIGO_PEDIDO
INNER JOIN PRODUTO PR ON IP.CODIGO_PRODUTO = PR.CODIGO;

-- 35
SELECT P.NOME, PED.DATA_PEDIDO, SUM(IP.QUANTIDADE)
FROM PEDIDO PED
INNER JOIN CLIENTE C ON PED.COD_CLIENTE = C.CODIGO
INNER JOIN PESSOA P ON C.CODIGO = P.CODIGO
INNER JOIN ITEM_PEDIDO IP ON PED.CODIGO = IP.CODIGO_PEDIDO
GROUP BY P.NOME, PED.DATA_PEDIDO;

-- 36
